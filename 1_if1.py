"""

Домашнее задание №1

Условный оператор: Возраст

* Попросить пользователя ввести возраст при помощи input и положить 
  результат в переменную
* Написать функцию, которая по возрасту определит, чем должен заниматься пользователь: 
  учиться в детском саду, школе, ВУЗе или работать
* Вызвать функцию, передав ей возраст пользователя и положить результат 
  работы функции в переменную
* Вывести содержимое переменной на экран

"""

def determine_activity(age):
    """Определяет, чем должен заниматься пользователь по возрасту"""
    if 0 <= age <= 6:
        return "Пора в детский сад"
    elif 7 <= age <= 16:
        return "Пора в школу"
    elif 17 <= age <= 24:
        return "Пора в ВУЗ"
    elif 25 <= age <= 100:
        return "Пора на работу"
    elif age > 100:
        return "Слишком много лет, отдыхай"
    else:
        return "Некорректный возраст"

def main():
    # Попросить пользователя ввести возраст
    age = int(input("Введите пожалуйста возраст: "))
    
    # Вызвать функцию и положить результат в переменную
    activity = determine_activity(age)
    
    # Вывести содержимое переменной на экран
    print(activity)

if __name__ == "__main__":
    main()